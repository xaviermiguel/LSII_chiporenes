    @Test
    void deleteRemovesDependentRowsAndFilesButPreservesOtherVideosAndUsers() throws Exception {
        var owner = registered();
        long id = upload(owner, "Delete").path("id").asLong();
        long keepId = upload(owner, "Keep").path("id").asLong();
        var video = videos.findById(id).orElseThrow();
        var keep = videos.findById(keepId).orElseThrow();
        long ownerId = owner.id;
        jdbc.update("INSERT INTO public.comments(video_id,author_id,text,created_at,source_metadata) VALUES (?,?,?,CURRENT_TIMESTAMP,'{}')", id, ownerId, "Parent");
        Long parent = jdbc.queryForObject("SELECT id FROM public.comments WHERE video_id=?", Long.class, id);
        // H2 checks this self-reference row by row; PostgreSQL checks the statement's final state.
        // The optional PostgreSQL run exercises replies against the real migration constraint.
        if (POSTGRES) {
            jdbc.update("INSERT INTO public.comments(video_id,parent_id,author_id,text,created_at,source_metadata) VALUES (?,?,?,?,CURRENT_TIMESTAMP,'{}')", id, parent, ownerId, "Reply");
        }
        jdbc.update("INSERT INTO public.comment_likes(comment_id,user_id) VALUES (?,?)", parent, ownerId);
        long tagId = 1L;
        if (POSTGRES) {
            tagId = jdbc.queryForObject("INSERT INTO public.tags(name) VALUES (?) RETURNING id", Long.class, "tag-" + id);
        }
        jdbc.update("INSERT INTO public.video_tags(video_id,tag_id) VALUES (?,?)", id, tagId);
        jdbc.update("INSERT INTO public.video_views(video_id) VALUES (?)", id);
        mutate(owner, delete("/api/videos/" + id)).andExpect(status().isNoContent()).andExpect(content().string(""));
        assertFalse(videos.existsById(id));
        for (String table : new String[]{"comments", "video_tags", "video_views"}) {
            assertEquals(0, jdbc.queryForObject("SELECT count(*) FROM public." + table + " WHERE video_id=?", Integer.class, id));
        }
        assertEquals(0, jdbc.queryForObject("SELECT count(*) FROM public.comment_likes WHERE comment_id=?", Integer.class, parent));
        assertFalse(Files.exists(STORE.resolve(video.getVideoPath())));
        assertFalse(Files.exists(STORE.resolve(video.getThumbnailPath())));
        assertTrue(Files.exists(STORE.resolve(keep.getVideoPath())));
        assertTrue(videos.existsById(keepId));
        assertTrue(users.existsById(ownerId));
        if (POSTGRES) assertEquals(1, jdbc.queryForObject("SELECT count(*) FROM public.tags WHERE id=?", Integer.class, tagId));
        mvc.perform(get("/api/videos/" + id)).andExpect(status().isNotFound());
    }

    @Test
    void rollbackRetainsDatabaseRowsAndFilesAndCleanupWaitsForCommit() throws Exception {
        var owner = registered();
        long id = upload(owner, "Rollback").path("id").asLong();
        var video = videos.findById(id).orElseThrow();
        jdbc.update("INSERT INTO public.video_views(video_id) VALUES (?)", id);
        new TransactionTemplate(transactions).executeWithoutResult(status -> {
            service.deleteVideo(id, owner.id);
            assertFalse(videos.existsById(id));
            assertTrue(Files.exists(STORE.resolve(video.getVideoPath())));
            assertTrue(Files.exists(STORE.resolve(video.getThumbnailPath())));
            status.setRollbackOnly();
        });
        assertTrue(videos.existsById(id));
        assertEquals(1, jdbc.queryForObject("SELECT count(*) FROM public.video_views WHERE video_id=?", Integer.class, id));
        assertTrue(Files.exists(STORE.resolve(video.getVideoPath())));
        assertTrue(Files.exists(STORE.resolve(video.getThumbnailPath())));
    }

