    @AfterAll
    static void removeTemporaryFiles(@Autowired javax.sql.DataSource dataSource) throws Exception {
        if (POSTGRES) {
            if (dataSource instanceof com.zaxxer.hikari.HikariDataSource pool) pool.close();
            try (var connection = DriverManager.getConnection(postgresBaseUrl() + "postgres",
                    PG.getProperty("ENV_PROTUBE_DB_USER"), PG.getProperty("ENV_PROTUBE_DB_PASS"));
                 var statement = connection.createStatement()) {
                // DATABASE_NAME is generated internally, never taken from local configuration.
                statement.execute("DROP DATABASE " + DATABASE_NAME);
            }
        }
        try (var paths = Files.walk(STORE)) {
            for (Path path : paths.sorted(Comparator.reverseOrder()).toList()) Files.deleteIfExists(path);
        }
    }

