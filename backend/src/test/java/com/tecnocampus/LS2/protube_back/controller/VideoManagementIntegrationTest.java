    private Client registered() throws Exception {
        var client = new Client();
        var csrf = csrf(client);
        var result = mvc.perform(post("/api/auth/register").session(client.session)
                        .header(csrf.path("headerName").asText(), csrf.path("token").asText())
                        .contentType("application/json").content(mapper.writeValueAsString(Map.of(
                                "displayName", "Test owner", "email", UUID.randomUUID() + "@example.com",
                                "password", "Test-password1!", "confirmPassword", "Test-password1!"))))
                .andExpect(status().isCreated()).andReturn();
        client.id = json(result).path("id").asLong();
        return client;
    }

    private JsonNode upload(Client client, String title) throws Exception {
        var csrf = csrf(client);
        var result = mvc.perform(multipart("/api/videos").file(videoFile()).file(thumbnailFile())
                        .param("title", title).param("description", "Description").session(client.session)
                        .header(csrf.path("headerName").asText(), csrf.path("token").asText()))
                .andExpect(status().isCreated()).andReturn();
        var body = json(result);
        assertEquals("/api/videos/" + body.path("id").asLong(), result.getResponse().getHeader("Location"));
        return body;
    }

    private org.springframework.test.web.servlet.ResultActions mutate(Client client, MockHttpServletRequestBuilder request) throws Exception {
        var csrf = csrf(client);
        return mvc.perform(request.session(client.session).contentType("application/json")
                .header(csrf.path("headerName").asText(), csrf.path("token").asText()));
    }

    private JsonNode csrf(Client client) throws Exception {
        return json(mvc.perform(get("/api/auth/csrf").session(client.session)).andExpect(status().isOk()).andReturn());
    }
    private JsonNode json(MvcResult result) throws Exception { return mapper.readTree(result.getResponse().getContentAsString()); }
