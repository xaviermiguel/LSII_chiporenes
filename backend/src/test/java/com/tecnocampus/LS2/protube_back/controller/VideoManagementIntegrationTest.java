    @Test
    void patchPersistsOnlySuppliedFieldsAndRejectsInvalidUpdates() throws Exception {
        var owner = registered();
        long id = upload(owner, "Before").path("id").asLong();
        mutate(owner, patch("/api/videos/" + id).content("{\"title\":\"After\"}"))
                .andExpect(status().isOk()).andExpect(jsonPath("$.description").value("Description"));
        assertEquals("After", videos.findById(id).orElseThrow().getTitle());
        mutate(owner, patch("/api/videos/" + id).content("{\"description\":\"Changed\"}"))
                .andExpect(status().isOk()).andExpect(jsonPath("$.title").value("After"));
        for (String body : new String[]{"{}", "{\"title\":\" \"}", "{\"description\":\"\"}",
                mapper.writeValueAsString(Map.of("title", "x".repeat(256))),
                "{\"title\":\"Should not persist\",\"description\":\" \"}"}) {
            mutate(owner, patch("/api/videos/" + id).content(body))
                    .andExpect(status().isBadRequest()).andExpect(jsonPath("$.code").value("INVALID_VIDEO_UPDATE"));
        }
        assertEquals("After", videos.findById(id).orElseThrow().getTitle());
        assertEquals("Changed", videos.findById(id).orElseThrow().getDescription());
    }

    @Test
    void ownershipMissingIdsAndCsrfProtectBothMutations() throws Exception {
        var owner = registered();
        var other = registered();
        long id = upload(owner, "Protected").path("id").asLong();
        for (String method : new String[]{"PATCH", "DELETE"}) {
            var request = request(org.springframework.http.HttpMethod.valueOf(method), "/api/videos/" + id);
            if (method.equals("PATCH")) request.content("{\"title\":\"Forbidden\"}");
            mutate(other, request).andExpect(status().isForbidden())
                    .andExpect(jsonPath("$.code").value("VIDEO_ACCESS_DENIED"));
            var missing = request(org.springframework.http.HttpMethod.valueOf(method), "/api/videos/9223372036854775807");
            if (method.equals("PATCH")) missing.content("{\"title\":\"Missing\"}");
            mutate(owner, missing).andExpect(status().isNotFound());
            mvc.perform(request(org.springframework.http.HttpMethod.valueOf(method), "/api/videos/" + id)
                            .session(owner.session).contentType("application/json").content("{\"title\":\"No CSRF\"}"))
                    .andExpect(status().isForbidden()).andExpect(jsonPath("$.code").value("INVALID_CSRF_TOKEN"));
        }
        assertTrue(videos.existsById(id));
        assertEquals("Protected", videos.findById(id).orElseThrow().getTitle());
        var anonymous = new Client();
        mutate(anonymous, delete("/api/videos/" + id)).andExpect(status().isUnauthorized());
        mutate(anonymous, patch("/api/videos/" + id).content("{\"title\":\"Anonymous\"}"))
                .andExpect(status().isUnauthorized());
    }

    @Test
    void editTagsAndCategoryReturnsAuthoritativeDetailAndPreservesOtherMetadata() throws Exception {
        var owner = registered();
        long id = upload(owner, "Metadata").path("id").asLong();
        long categoryId = new TransactionTemplate(transactions).execute(status -> {
            var category = new com.tecnocampus.LS2.protube_back.model.Category();
            category.setName("Editing-" + UUID.randomUUID());
            var entityManager = org.springframework.orm.jpa.EntityManagerFactoryUtils
                    .getTransactionalEntityManager(entityManagerFactory);
            entityManager.persist(category);
            var video = videos.findById(id).orElseThrow();
            video.setSourceMetadata(new java.util.LinkedHashMap<>(Map.of("original", "preserved")));
            return category.getId();
        });
        mvc.perform(get("/api/videos/categories"))
                .andExpect(status().isOk()).andExpect(jsonPath("$[?(@.id == " + categoryId + ")]").exists());
        mutate(owner, patch("/api/videos/" + id).content(mapper.writeValueAsString(Map.of(
                "title", "Updated", "description", "Changed", "tags", java.util.List.of(" Java ", "Java", "", "a,b"),
                "categoryId", categoryId))))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.ownerId").isNumber())
                .andExpect(jsonPath("$.category.id").value(categoryId))
                .andExpect(jsonPath("$.tags[0]").value("Java"))
                .andExpect(jsonPath("$.tags[1]").value("a,b"))
                .andExpect(jsonPath("$.tags.length()").value(2));
        assertEquals("preserved", videos.findById(id).orElseThrow().getSourceMetadata().get("original"));
        mutate(owner, patch("/api/videos/" + id).content("{\"title\":\"Partial\"}"))
                .andExpect(status().isOk()).andExpect(jsonPath("$.category.id").value(categoryId));
        mvc.perform(get("/api/videos/" + id)).andExpect(status().isOk())
                .andExpect(jsonPath("$.title").value("Partial"))
                .andExpect(jsonPath("$.tags[1]").value("a,b"));
        mutate(owner, patch("/api/videos/" + id).content("{\"tags\":[],\"categoryId\":null}"))
                .andExpect(status().isOk()).andExpect(jsonPath("$.tags").isEmpty())
                .andExpect(jsonPath("$.category").isEmpty());
    }

