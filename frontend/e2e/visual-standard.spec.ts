import { test, expect } from '@playwright/test';

for (const width of [320, 390, 768, 1440]) {
  test(`visual standard at ${width}px: catalog, focus, detail and comments`, async ({ page }, testInfo) => {
    await page.setViewportSize({ width, height: 900 });
    // Synthetic preview: the HTTP fixtures are byte samples, not decodable images.
    await page.route('**/media/*.webp', (route) =>
      route.fulfill({
        contentType: 'image/svg+xml',
        body: '<svg xmlns="http://www.w3.org/2000/svg" width="640" height="360" viewBox="0 0 640 360"><rect width="640" height="360" fill="#dcebe0"/><circle cx="480" cy="80" r="110" fill="#9ac4a8"/><path d="M0 300L220 100L440 360H0Z" fill="#387758"/><path d="M200 360L450 170L640 360Z" fill="#24543d"/></svg>',
      })
    );
    await page.goto('/');
    const first = page.getByRole('button', { name: 'E2E first video', exact: true });
    await expect(first).toBeVisible();
    await expect(page.getByRole('banner')).toBeVisible();
    await expect(page.getByRole('main')).toBeVisible();
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy();
    await page.keyboard.press('Tab');
    await expect(page.getByRole('link', { name: 'Saltar al contenido' })).toBeFocused();
    await page.keyboard.press('Enter');
    await expect(page.getByRole('main')).toBeFocused();
    await page.keyboard.press('Tab');
    await expect(first).toBeFocused();
    expect(await first.evaluate((element) => getComputedStyle(element).outlineStyle)).toBe('solid');
    const touchTarget = await first.boundingBox();
    expect(touchTarget!.height).toBeGreaterThanOrEqual(44);
    await page.screenshot({ path: testInfo.outputPath(`catalog-${width}.png`), fullPage: true });
    await page.keyboard.press('Enter');
    await expect(page.getByRole('heading', { name: 'E2E first video', exact: true })).toBeVisible();
    await expect(page.getByText('E2E comment', { exact: true })).toBeVisible();
    await expect(page.getByLabel('Reproductor: E2E first video')).toHaveAttribute('controls', '');
    const player = await page.getByLabel('Reproductor: E2E first video').boundingBox();
    expect(player!.width).toBeLessThanOrEqual(width);
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy();
    await page.screenshot({ path: testInfo.outputPath(`detail-${width}.png`), fullPage: true });
    await page.getByRole('button', { name: 'Volver al catálogo' }).click();
    await expect(first).toBeVisible();
    await page.getByRole('button', { name: 'E2E second video', exact: true }).click();
    await expect(page.getByText('Este vídeo todavía no tiene comentarios.')).toBeVisible();
  });
}

test('mobile request error and long content stay inside the shared layout', async ({ page }) => {
  await page.setViewportSize({ width: 320, height: 800 });
  await page.route('**/api/videos?*', (route) => route.fulfill({ status: 503, json: {} }));
  await page.goto('/');
  await expect(page.getByRole('alert')).toBeVisible();
  await expect(page.getByRole('button', { name: 'Reintentar' })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy();
  await page.unroute('**/api/videos?*');
  await page.route('**/api/videos?*', (route) =>
    route.fulfill({
      json: {
        items: [
          {
            id: 200,
            title: 'Título'.repeat(50),
            user: 'Autor'.repeat(50),
            duration: 1,
            thumbnailUrl: '/media/fixture.webp',
          },
        ],
        page: 0,
        size: 12,
        hasNext: false,
      },
    })
  );
  await page.getByRole('button', { name: 'Reintentar' }).click();
  await expect(page.locator('.video-card-title')).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy();
  await page.emulateMedia({ reducedMotion: 'reduce' });
  expect(await page.locator('.video-card').evaluate((element) => getComputedStyle(element).transitionDuration)).toBe(
    '0s'
  );
});

// Valid silent WebM generated by Chromium: no download, codec fixture or user media required.
test('native video playback remains functional at mobile and desktop sizes', async ({ page }) => {
  await page.goto('/');
  const bytes = await page.evaluate(async () => {
    const canvas = document.createElement('canvas');
    canvas.width = 160;
    canvas.height = 90;
    const context = canvas.getContext('2d')!;
    const stream = canvas.captureStream(10);
    const recorder = new MediaRecorder(stream, { mimeType: 'video/webm' });
    const chunks: BlobPart[] = [];
    const stopped = new Promise<void>((resolve) => {
      recorder.onstop = () => resolve();
    });
    recorder.ondataavailable = (event) => chunks.push(event.data);
    recorder.start();
    const timer = window.setInterval(() => {
      context.fillStyle = '#166344';
      context.fillRect(0, 0, canvas.width, canvas.height);
    }, 50);
    await new Promise((resolve) => window.setTimeout(resolve, 600));
    recorder.stop();
    await stopped;
    window.clearInterval(timer);
    stream.getTracks().forEach((track) => track.stop());
    return Array.from(new Uint8Array(await new Blob(chunks, { type: 'video/webm' }).arrayBuffer()));
  });
  await page.route('**/media/fixture.mp4', (route) =>
    route.fulfill({
      contentType: 'video/webm',
      body: Buffer.from(bytes),
    })
  );
  for (const width of [390, 1440]) {
    await page.setViewportSize({ width, height: 900 });
    await page.getByRole('button', { name: 'E2E first video', exact: true }).click();
    const player = page.getByLabel('Reproductor: E2E first video');
    await expect(player).toBeVisible();
    await player.evaluate((element) => (element as HTMLVideoElement).play());
    await expect.poll(() => player.evaluate((element) => (element as HTMLVideoElement).currentTime)).toBeGreaterThan(0);
    expect(await player.evaluate((element) => (element as HTMLVideoElement).error)).toBeNull();
    await expect(page.getByText('E2E comment', { exact: true })).toBeVisible();
    await expect(page.getByText('No se pudo reproducir el archivo de vídeo.')).toHaveCount(0);
    await page.getByRole('button', { name: 'Volver al catálogo' }).click();
  }
});
